"""Deterministic, source-linked context for an annual movement investigation.

This module assembles observations, not explanations of why they occurred.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
from typing import Any

import pandas as pd

from filinglens.ui.components import LABELS, METRIC_FORMULAS, metric_display_value


COMPONENTS = {
    "free_cash_flow": ("operating_cash_flow", "capital_expenditures"),
    "gross_profit": ("revenue", "cost_of_revenue"),
    "gross_margin": ("gross_profit", "revenue"),
    "operating_margin": ("operating_income", "revenue"),
    "net_margin": ("net_income", "revenue"),
    "operating_cash_flow_margin": ("operating_cash_flow", "revenue"),
    "free_cash_flow_margin": ("free_cash_flow", "revenue"),
    "current_ratio": ("current_assets", "current_liabilities"),
    "debt_to_assets": ("long_term_debt", "total_assets"),
    "debt_to_equity": ("long_term_debt", "stockholders_equity"),
    "return_on_assets": ("net_income", "total_assets"),
    "return_on_equity": ("net_income", "stockholders_equity"),
}
RELATED = {
    "operating_cash_flow": ("net_income", "revenue", "capital_expenditures"),
    "free_cash_flow": ("operating_cash_flow", "capital_expenditures", "net_income"),
    "revenue": ("cost_of_revenue", "gross_profit", "operating_income"),
    "cost_of_revenue": ("revenue", "gross_profit", "operating_income"),
    "operating_income": ("revenue", "gross_profit", "net_income"),
    "net_income": ("operating_income", "operating_cash_flow", "revenue"),
    "long_term_debt": ("cash", "operating_cash_flow", "total_assets"),
}
QUERIES = {
    "operating_cash_flow": "cash flows operating activities working capital receivables inventory collections payments",
    "free_cash_flow": "cash flows operating activities capital expenditures investments property equipment",
    "revenue": "revenue sales changes growth pricing volume demand",
    "cost_of_revenue": "cost revenue sales gross margin expenses pricing",
    "gross_profit": "gross profit margin cost sales revenue",
    "operating_income": "operating income expenses margin costs",
    "net_income": "net income earnings taxes expenses",
    "capital_expenditures": "capital expenditures property equipment investments cash flows",
    "long_term_debt": "debt borrowings repayment liquidity interest financing",
}
PASSAGE_ANCHORS = {
    "operating_cash_flow": ("operating activities", "operating cash", "cash generated by operations", "cash from operations"),
    "free_cash_flow": ("operating activities", "operating cash", "capital expenditures", "property, plant", "property and equipment"),
    "revenue": ("revenue", "net sales", "total sales"),
    "cost_of_revenue": ("cost of revenue", "cost of sales", "gross margin"),
    "gross_profit": ("gross profit", "gross margin"),
    "operating_income": ("operating income", "operating expenses", "operating margin"),
    "net_income": ("net income", "net earnings"),
    "capital_expenditures": ("capital expenditures", "property, plant", "property and equipment"),
    "long_term_debt": ("debt", "borrowings", "repayments"),
}


def _number(value: Any) -> float | None:
    try:
        value = float(value)
        return value if math.isfinite(value) else None
    except (ValueError, TypeError):
        return None


def _label(metric: str) -> str:
    return LABELS.get(metric, metric.replace("_", " ").title())


def build_evidence_trail(bundle: dict[str, Any], metric: str, period: int,
                         filing_urls: dict[str, str]) -> dict[str, Any]:
    """Use the anomaly's actual previous available period, including any gap.

    Calculation inputs follow the existing analytics' row-shift semantics, while
    anomaly comparisons follow detect_anomalies' nonmissing series semantics.
    """
    financials, ratios, facts = (bundle[key] for key in ("financials", "ratios", "facts"))
    values = pd.concat([financials, ratios], axis=1).sort_index()
    if metric not in values:
        raise ValueError("Choose a metric in the loaded annual movement screen.")
    series = pd.to_numeric(values[metric], errors="coerce").dropna()
    if period not in series.index or series.index.get_loc(period) == 0:
        raise ValueError("No prior available observation exists for this movement.")
    prior_period = int(series.index[series.index.get_loc(period) - 1])
    flags = bundle["anomalies"]
    match = flags[(flags["metric"] == metric) & (flags["period"] == period)] if not flags.empty else flags
    if match.empty:
        raise ValueError("This movement is not in the loaded annual screen.")
    flag = match.iloc[0]
    warnings: list[str] = []

    def observation(name: str, year: int) -> dict[str, Any]:
        frame = ratios if name in ratios else financials
        value = _number(frame.loc[year, name]) if name in frame and year in frame.index else None
        selected = facts[(facts["metric"] == name) & (facts["fiscal_year"] == year)] if not facts.empty else facts
        source = None
        if not selected.empty:
            fact = selected.iloc[0]
            accession = str(fact["accession_number"])
            cik = str(bundle["company"].cik)
            url = filing_urls.get(accession)
            if not url and cik.isdigit() and re.fullmatch(r"\d{10}-\d{2}-\d{6}", accession):
                url = f"https://www.sec.gov/Archives/edgar/data/{int(cik)}/{accession.replace('-', '')}/{accession}-index.html"
            source = {"concept": str(fact["xbrl_concept"]), "accession": accession,
                      "filed": str(fact["filing_date"]), "form": str(fact["form"]), "url": url,
                      "start": None if pd.isna(fact["period_start"]) else str(fact["period_start"]),
                      "end": str(fact["period_end"]), "unit": str(fact["unit"])}
        inputs = []
        # A reported gross-profit fact takes precedence over the fallback formula.
        if source is None and value is not None:
            dependencies = COMPONENTS.get(name, ())
            if name.endswith("_growth"):
                dependencies = (name.removesuffix("_growth"),)
            years = [year]
            if name.endswith("_growth") or name in {"return_on_assets", "return_on_equity"}:
                location = financials.index.get_loc(year)
                if location > 0:
                    years.insert(0, int(financials.index[location - 1]))
            for component in dependencies:
                for input_year in years:
                    if name in {"return_on_assets", "return_on_equity"} and component == "net_income" and input_year != year:
                        continue
                    inputs.append(observation(component, input_year))
        return {"id": f"{name}:{year}", "metric": name, "label": _label(name), "year": year,
                "value": value, "display": metric_display_value(name, value, ratio=name in ratios),
                "origin": "reported" if source else "calculated" if inputs else "unavailable",
                "formula": METRIC_FORMULAS.get(name) if inputs else None, "source": source, "inputs": inputs}

    def movement(name: str) -> dict[str, Any]:
        before, after = observation(name, prior_period), observation(name, period)
        left, right = before["value"], after["value"]
        difference = right - left if left is not None and right is not None else None
        change_display = metric_display_value(name, difference, ratio=name in ratios)
        if name in ratios and name not in {"current_ratio", "debt_to_equity"} and difference is not None:
            change_display = f"{difference * 100:+.1f} percentage points"
        return {"id": f"movement:{name}", "metric": name, "label": _label(name),
                "prior": before, "current": after, "absolute_change": difference,
                "change_display": change_display,
                "percentage_change": difference / abs(left) if difference is not None and left else None}

    base = metric.removesuffix("_growth")
    related_names = COMPONENTS.get(metric, RELATED.get(base, ("revenue", "net_income", "operating_cash_flow")))
    related = [movement(name) for name in related_names if name != metric and name in values][:3]
    primary = movement(metric)
    if period - prior_period != 1:
        warnings.append(f"The previous available observation is {prior_period}, not {period - 1}. This comparison spans a gap and is not a consecutive-year change.")
    warnings.append("Values use the currently selected SEC facts, which may have been reported or revised in later filings. This is not a historical as-of snapshot.")
    warnings.append("Related movements are selected by a fixed accounting checklist. Co-movement and retrieved passages do not establish a cause.")
    identity = {"ticker": bundle["company"].ticker, "movement": primary, "related": related}
    trail_id = hashlib.sha256(json.dumps(identity, sort_keys=True).encode()).hexdigest()[:24]
    query_base = COMPONENTS.get(metric, (base,))[0] if metric not in QUERIES else metric
    return {"id": trail_id, "ticker": bundle["company"].ticker, "metric": metric,
            "period": period, "prior_period": prior_period,
            "severity": str(flag["severity"]), "method": str(flag["method"]),
            "movement": primary, "related": related, "notices": warnings,
            "query": QUERIES.get(query_base, f"{_label(base)} changes management discussion liquidity financial condition"),
            "passage_anchors": list(PASSAGE_ANCHORS.get(query_base, (_label(query_base).lower(),))),
            "passages": [], "filings": [], "passage_status": "not_requested", "passage_issues": []}
